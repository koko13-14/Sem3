#pragma once

/**
 * @brief Длина окна для отчёта о продажах: последние N дней до опорной
 * даты (второе задание варианта «Аптека»).
 */
enum class ReportRange
{
    Week,   ///< Последние 7 дней, включая опорный.
    Month,  ///< Последние 30 дней, включая опорный.
    Year    ///< Последние 365 дней, включая опорный.
};
